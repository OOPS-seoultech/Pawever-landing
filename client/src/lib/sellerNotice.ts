/**
 * 이 표시를 화면에 그려도 되는가.
 *
 * 한 칸이라도 비어 있으면 그리지 않는다. 절반만 적힌 표시는 표시가 아니라
 * 우리가 무엇을 못 갖췄는지 알리는 안내가 된다.
 */
export function sellerNoticeReady(
  seller: readonly NoticeField[] = SELLER_FIELDS,
  terms: readonly NoticeField[] = TRANSACTION_TERMS
): boolean {
  return [...seller, ...terms].every(field => field.value.trim().length > 0);
}
